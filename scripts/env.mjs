// Local development keys. The demo apps' admin key (DEMO_SHOP_KEY) and the Jira and Confluence simulators' API token
// (SIM_TOKEN) are never committed: the first run of scripts/dev.mjs writes random values to a git-ignored .env at the
// repository root, and every script loads it. Values already in the environment win.

import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, appendFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const file = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", ".env");
const GENERATED = ["DEMO_SHOP_KEY", "SIM_TOKEN"];

function parse() {
  if (!existsSync(file)) return {};
  const out = {};
  for (const line of readFileSync(file, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
    if (m && !line.trim().startsWith("#")) out[m[1]] = m[2].replace(/^["']|["']$/g, "");
  }
  return out;
}

// Loads .env into process.env without overriding what is already set.
export function loadEnv() {
  for (const [k, v] of Object.entries(parse())) if (v !== "" && process.env[k] === undefined) process.env[k] = v;
}

// Adds a random value for each missing local key to .env, then loads it. Returns the names it created.
export function ensureEnv() {
  const have = { ...parse(), ...Object.fromEntries(GENERATED.filter((k) => process.env[k]).map((k) => [k, process.env[k]])) };
  const created = GENERATED.filter((k) => !have[k]);
  if (created.length) {
    const head = existsSync(file) ? "" : "# Local development keys, generated by scripts/dev.mjs. Git-ignored: keep this file local.\n";
    appendFileSync(file, head + created.map((k) => `${k}=${randomBytes(18).toString("hex")}`).join("\n") + "\n");
  }
  loadEnv();
  return created;
}

// `node scripts/env.mjs`: create .env with local keys without starting anything (for Docker Compose).
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const made = ensureEnv();
  console.log(made.length ? `.env: created ${made.join(" and ")}.` : ".env already has DEMO_SHOP_KEY and SIM_TOKEN.");
}
